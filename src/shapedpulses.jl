"""
    A file containing the pulse shapes, as functions of 𝑡,
    Stored in a Dict at the end. 
    Also contains a custom struct and some custom methods to handle 
    pulse shapes correctly.
"""

function process_pulse_shapes(D :: Dict{S, M}) where {S<:AbstractString, M<:AbstractMatrix}
    out = Dict{S, Vector}()
    for k in keys(D)
        a = ( D[k][:, 1] )
        ϕ = ( D[k][:, 2] )
    # a matrix of (amplitiude, phase) values for each t
    # want to recover the complex form
        out[k] = a .* cosd.(ϕ) .+ 1im .* a .* sind.(ϕ)
    end
    return out
end

